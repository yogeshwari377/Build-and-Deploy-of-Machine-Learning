"""
EduPredict – Student Academic Performance Prediction System
============================================================
Flask Backend (app.py)

Endpoints:
  - GET  /        : Serves the web interface (HTML template).
  - POST /predict : Accepts 5 student features, validates inputs, and returns
                    the dynamic ML prediction as JSON.
  - GET  /health  : Returns application and ML pipeline health status.

Model Location:
  Primary: model/trained_model.pkl
  Fallbacks: models/best_model_pipeline.joblib, models/trained_model.pkl
"""

import sys
from pathlib import Path
from typing import Optional, Tuple, Dict, Any

from flask import Flask, request, jsonify, render_template
import pandas as pd
import joblib

app = Flask(__name__)

# ==============================================================================
# Model Configuration & Loader
# ==============================================================================
MODEL_CANDIDATE_PATHS = [
    Path("model") / "trained_model.pkl",           # Primary requested path
    Path("models") / "trained_model.pkl",          # Alternate pickle path
    Path("models") / "best_model_pipeline.joblib", # Pipeline generated by train_model.py
    Path("model") / "best_model_pipeline.joblib",
]

_model = None
_loaded_model_path: Optional[str] = None


def load_trained_model():
    """
    Load the trained ML pipeline from disk.
    Searches primary and fallback candidate paths.
    """
    global _model, _loaded_model_path
    for candidate in MODEL_CANDIDATE_PATHS:
        if candidate.exists():
            try:
                _model = joblib.load(candidate)
                _loaded_model_path = str(candidate.resolve())
                print(f"[EduPredict] Successfully loaded ML pipeline from: {_loaded_model_path}")
                return _model
            except Exception as e:
                print(f"[EduPredict] Warning: Failed to load candidate {candidate}: {e}")
    print("[EduPredict] Notice: No trained model found at candidate paths. /predict will return 503 until trained.")
    return None


# Attempt loading on module load
load_trained_model()


# ==============================================================================
# Validation Helpers
# ==============================================================================
REQUIRED_FEATURE_MAP = {
    "hours_studied": "Hours Studied",
    "previous_scores": "Previous Scores",
    "extracurricular_activities": "Extracurricular Activities",
    "sleep_hours": "Sleep Hours",
    "sample_question_papers_practiced": "Sample Question Papers Practiced",
}


def validate_prediction_input(data: Any) -> Tuple[Optional[Dict[str, Any]], Optional[str]]:
    """
    Validate and extract the 5 student input features.
    Supports both snake_case and exact dataset column names.
    Returns (cleaned_dict, None) on success or (None, error_message) on failure.
    """
    if not isinstance(data, dict):
        return None, "Request payload must be a JSON object."

    cleaned: Dict[str, Any] = {}

    # 1. Hours Studied (0 <= x <= 24)
    raw_hours = data.get("hours_studied", data.get("Hours Studied"))
    if raw_hours is None:
        return None, "Missing required field: 'hours_studied' (or 'Hours Studied')."
    try:
        hours_val = float(raw_hours)
    except (ValueError, TypeError):
        return None, "'hours_studied' must be a valid number."
    if not (0 <= hours_val <= 24):
        return None, f"'hours_studied' must be between 0 and 24 (received: {hours_val})."
    cleaned["Hours Studied"] = hours_val

    # 2. Previous Scores (0 <= x <= 100)
    raw_scores = data.get("previous_scores", data.get("Previous Scores"))
    if raw_scores is None:
        return None, "Missing required field: 'previous_scores' (or 'Previous Scores')."
    try:
        score_val = float(raw_scores)
    except (ValueError, TypeError):
        return None, "'previous_scores' must be a valid number."
    if not (0 <= score_val <= 100):
        return None, f"'previous_scores' must be between 0 and 100 (received: {score_val})."
    cleaned["Previous Scores"] = score_val

    # 3. Extracurricular Activities ('Yes' or 'No')
    raw_extra = data.get("extracurricular_activities", data.get("Extracurricular Activities"))
    if raw_extra is None:
        return None, "Missing required field: 'extracurricular_activities' (or 'Extracurricular Activities')."
    if not isinstance(raw_extra, str):
        return None, "'extracurricular_activities' must be a string ('Yes' or 'No')."
    norm_extra = raw_extra.strip().capitalize()
    if norm_extra not in ["Yes", "No"]:
        return None, f"'extracurricular_activities' must be either 'Yes' or 'No' (received: '{raw_extra}')."
    cleaned["Extracurricular Activities"] = norm_extra

    # 4. Sleep Hours (0 <= x <= 24)
    raw_sleep = data.get("sleep_hours", data.get("Sleep Hours"))
    if raw_sleep is None:
        return None, "Missing required field: 'sleep_hours' (or 'Sleep Hours')."
    try:
        sleep_val = float(raw_sleep)
    except (ValueError, TypeError):
        return None, "'sleep_hours' must be a valid number."
    if not (0 <= sleep_val <= 24):
        return None, f"'sleep_hours' must be between 0 and 24 (received: {sleep_val})."
    cleaned["Sleep Hours"] = sleep_val

    # 5. Sample Question Papers Practiced (x >= 0)
    raw_papers = data.get("sample_question_papers_practiced", data.get("Sample Question Papers Practiced"))
    if raw_papers is None:
        return None, "Missing required field: 'sample_question_papers_practiced' (or 'Sample Question Papers Practiced')."
    try:
        papers_val = float(raw_papers)
    except (ValueError, TypeError):
        return None, "'sample_question_papers_practiced' must be a valid number."
    if papers_val < 0:
        return None, f"'sample_question_papers_practiced' cannot be negative (received: {papers_val})."
    cleaned["Sample Question Papers Practiced"] = papers_val

    return cleaned, None


# ==============================================================================
# Routes
# ==============================================================================
@app.route("/", methods=["GET"])
def index():
    """Serve the frontend webpage."""
    return render_template("index.html")


@app.route("/health", methods=["GET"])
def health():
    """Return application and model health status."""
    global _model, _loaded_model_path
    # Retry model load if not currently loaded
    if _model is None:
        load_trained_model()

    return jsonify({
        "status": "healthy",
        "service": "EduPredict Backend",
        "model_loaded": _model is not None,
        "model_path": _loaded_model_path,
    }), 200


@app.route("/predict", methods=["POST"])
def predict():
    """
    Receive student input features, validate them, and predict Performance Index.
    Never returns hardcoded values.
    """
    global _model
    if _model is None:
        load_trained_model()
        if _model is None:
            return jsonify({
                "status": "error",
                "error": "ML model is not loaded. Please train the model and save to model/trained_model.pkl."
            }), 503

    if not request.is_json:
        return jsonify({
            "status": "fail",
            "error": "Request Content-Type must be 'application/json'."
        }), 400

    payload = request.get_json(silent=True)
    if payload is None:
        return jsonify({
            "status": "fail",
            "error": "Invalid or empty JSON body."
        }), 400

    cleaned_data, error_msg = validate_prediction_input(payload)
    if error_msg:
        return jsonify({
            "status": "fail",
            "error": error_msg
        }), 400

    # Build single-row DataFrame with exact columns expected by the preprocessor
    input_df = pd.DataFrame([cleaned_data])

    try:
        # Dynamic inference with the trained pipeline
        raw_prediction = float(_model.predict(input_df)[0])
        # Performance index in dataset is between 10 and 100
        formatted_prediction = round(raw_prediction, 2)

        return jsonify({
            "status": "success",
            "prediction": formatted_prediction,
            "performance_index": formatted_prediction,
            "inputs": cleaned_data
        }), 200
    except Exception as e:
        return jsonify({
            "status": "error",
            "error": f"Prediction failed during model inference: {str(e)}"
        }), 500


